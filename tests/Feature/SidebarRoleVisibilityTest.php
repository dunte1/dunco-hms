    public function test_restricted_roles_blocked_from_admin_and_cross_domain_routes(): void
    {
        $matrix = [
            // role => [allowed routes, denied routes]
            // Note: Doctor intentionally has postmortem/death-certificate perms (clinical duty)
            'Doctor' => [
                'allowed' => ['/hms/patients', '/hms/pharmacy/prescriptions'],
                'denied' => ['/admin/roles'],
            ],
            'Pharmacist' => [
                // Pharmacist has view patients (dispensing context) â€” allowed by design
                'allowed' => ['/hms/pharmacy/prescriptions', '/hms/patients'],
                'denied' => ['/hms/appointments', '/admin/roles', '/hms/mortuary'],
            ],
            'Nurse' => [
                'allowed' => ['/hms/patients', '/hms/ipd', '/hms/triage'],
                'denied' => ['/admin/roles', '/hms/mortuary'],
            ],
            'Security Officer' => [
                // Has view patients (visitor/patient context). IPD middleware ORs view patients,
                // so IPD read is allowed by current authorization design â€” documented, not assumed.
                'allowed' => [],
                'denied' => ['/hms/mortuary', '/admin/roles', '/hms/pharmacy/prescriptions'],
            ],
            'Receptionist' => [
                'allowed' => ['/hms/patients', '/hms/appointments'],
                'denied' => ['/admin/roles', '/hms/mortuary'],
            ],
        ];

        foreach ($matrix as $role => $cases) {
            $user = $this->userWithRole($role);
            foreach ($cases['allowed'] as $route) {
                $resp = $this->actingAs($user)->get($route);
                if ($resp->status() === 404) { continue; }
                $this->assertTrue(
                    $resp->status() === 200,
                    "{$role} should access {$route}, got {$resp->status()}"
                );
            }
            foreach ($cases['denied'] as $route) {
                $resp = $this->actingAs($user)->get($route);
                $this->assertTrue(
                    in_array($resp->status(), [403, 404], true),
                    "{$role} should be denied {$route}, got {$resp->status()}"
                );
            }
        }
    }

